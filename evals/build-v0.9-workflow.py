"""Generate the v0.9 routing eval workflowScript.

Embeds the trigger dataset, both catalogs (treatment = current descriptions,
baseline = v0.7 descriptions), and the judge prompt from v0.8's recorded
routing_evaluation into a single portable .mjs workflow file. The workflow
launches one delegate subagent per case (6 slots: 3 runs x 2 arms), each
writing structured judgments to evals/results/v0.9-raw/<case_id>.json.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RAW_DIR = ROOT / "evals" / "results" / "v0.9-raw"

trigger = json.loads((ROOT / "evals" / "skill-triggering.json").read_text(encoding="utf-8"))
v08 = json.loads((ROOT / "evals" / "results" / "v0.8-routing-summary.json").read_text(encoding="utf-8"))
v07 = json.loads((ROOT / "evals" / "results" / "v0.7-routing-summary.json").read_text(encoding="utf-8"))
current = json.loads((ROOT / "evals" / "catalog-current.json").read_text(encoding="utf-8"))

cases = trigger["cases"]
distractors = v08["distractors"]
judge_system = v08["routing_evaluation"]["system_prompt"]
judge_template = v08["routing_evaluation"]["user_prompt_template"]
judge_model = v08["routing_evaluation"]["model"]
concurrency = v08["routing_evaluation"]["concurrency"]

treatment_catalog = current["catalog_snapshot"]["entries"] + distractors
baseline_catalog = v07["catalog_snapshot"]["entries"] + distractors

# canonical JSON for embedding as JS literals (ensure_ascii keeps it ASCII-safe)
def js(v):
    return json.dumps(v, ensure_ascii=True, separators=(",", ":"))

header = f"""// GENERATED by evals/build-v0.9-workflow.py - do not edit by hand.
// v0.9 routing eval: 122 cases x 3 runs x 2 arms = {len(cases)*6} slots.
// Judge identity reuses v0.8's recorded prompt ({judge_model}).
const CASES = {js(cases)};
const TREATMENT_CATALOG = {js(treatment_catalog)};
const BASELINE_CATALOG = {js(baseline_catalog)};
const JUDGE_SYSTEM = {js(judge_system)};
const JUDGE_TEMPLATE = {js(judge_template)};
const CONCURRENCY = {concurrency};
const RAW_DIR = "evals/results/v0.9-raw";

function slotBlock(catalog, item, run, arm) {{
  const user = JUDGE_TEMPLATE
    .replace("${{JSON.stringify(catalog)}}", JSON.stringify(catalog))
    .replace("${{item.source}}", item.source)
    .replace("${{item.prompt}}", item.prompt);
  return [
    "--- Slot: " + item.id + "-" + arm + "-r" + run + " ---",
    user,
    'Reply for this slot with exactly: {{"slot_id":"' + item.id + '-' + arm + '-r' + run + '","selected_skill":<skill name or null>,"reason":"<one short line>"}}'
  ].join("\\n");
}}

function buildTask(item) {{
  const blocks = [];
  for (let run = 1; run <= 3; run++) {{
    for (const [arm, catalog] of [["treatment", TREATMENT_CATALOG], ["baseline", BASELINE_CATALOG]]) {{
      blocks.push(slotBlock(catalog, item, run, arm));
    }}
  }}
  return JUDGE_SYSTEM + "\\n\\n" + blocks.join("\\n\\n") + "\\n\\nReturn a single JSON array of 6 objects (one per slot), field names exactly slot_id / selected_skill / reason. No prose, no markdown fences.";
}}

const OUTPUT_SCHEMA = {{
  type: "object",
  properties: {{
    judgments: {{
      type: "array",
      items: {{
        type: "object",
        properties: {{
          slot_id: {{ type: "string" }},
          selected_skill: {{ anyOf: [{{ type: "string" }}, {{ type: "null" }}] }},
          reason: {{ type: "string" }}
        }},
        required: ["slot_id", "selected_skill", "reason"]
      }}
    }}
  }},
  required: ["judgments"]
}};

const WAVE = [];
for (const item of CASES) {{
  WAVE.push({{
    key: item.id,
    agent: "delegate",
    model: {js(judge_model)},
    outputSchema: OUTPUT_SCHEMA,
    output: RAW_DIR + "/" + item.id + ".json",
    task: buildTask(item)
  }});
}}

function runWave(batch) {{
  return runs.all(batch);
}}

async function sleep(ms) {{
  await new Promise(r => setTimeout(r, ms));
}}

let pending = WAVE;
let failures = [];
let attempts = 0;
const backoffs = [0, 5000, 15000];
for (let wave = 0; wave < 3 && pending.length > 0; wave++) {{
  if (wave > 0) await sleep(backoffs[wave]);
  attempts += pending.length;
  const results = await runWave(pending);
  const failed = [];
  for (let i = 0; i < results.length; i++) {{
    const r = results[i];
    if (!r.ok || !r.structuredOutput) {{
      failed.push({ key: pending[i].key, error: (r.error && r.error.message) || "no structured output" });
    }}
  }}
  failures = failed;
  pending = WAVE.filter(w => failed.some(f => f.key === w.key));
}}

return {{
  total_slots: CASES.length * 6,
  attempts,
  failures,
  remaining: pending.length,
  raw_dir: RAW_DIR,
  note: "judgments written per case; parent reads evals/results/v0.9-raw/*.json"
}};
"""

(ROOT / "evals" / "run-v0.9-workflow.mjs").write_text(header, encoding="utf-8")
print(f"wrote evals/run-v0.9-workflow.mjs ({len(header)} bytes)")
print(f"cases={len(cases)} slots={len(cases)*6} model={judge_model} concurrency={concurrency}")
